/** Trang thật dán CSS blob vào MỌI ô (th + td) - parser phải rửa sạch 66/66. */
export function junkGoodsHtml(): string {
  const rows = [...GOODS_HTML.matchAll(/<tr><td>([\s\S]*?)<\/td><td>(.*?)<\/td>.*?<\/tr>/g)];
  if (rows.length !== 66) throw new Error("fixture: expected 66 rows, got " + rows.length);
  const th = ["Mặt hàng", "Giá", "% Ngày", "% Tháng", "% Năm", "Ngày cập nhật"]
    .map((h) => `<th>${CSS_TEXT_BLOB}${h}</th>`)
    .join("");
  return (
    `<table><tr>${th}</tr>` +
    rows
      .map((m) => `<tr><td>${CSS_TEXT_BLOB}${m[1]}</td><td>${CSS_TEXT_BLOB}${m[2]}</td><td>${CSS_TEXT_BLOB}--</td><td>${CSS_TEXT_BLOB}--</td><td>${CSS_TEXT_BLOB}--</td><td>${CSS_TEXT_BLOB}05/09/2026</td></tr>`)
      .join("\n") +
    "</table>"
  );
}
